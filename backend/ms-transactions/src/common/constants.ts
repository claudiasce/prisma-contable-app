    AuthQueue: process.env.MQ_AUTH_QUEUE,
    ManagementQueue: process.env.MQ_ING_ALL_MANAGEMENT_QUEUE,
    WhatsappQueue: process.env.MQ_WHATSAPP_MS_QUEUE,
